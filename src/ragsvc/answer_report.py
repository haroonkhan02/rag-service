"""Markdown for `ragsvc-answer-eval report`."""

from __future__ import annotations


def pct(s: dict | None) -> str:
    if not s or s["share"] is None:
        return "-"
    return f"{100 * s['share']:.1f} % ({s['count']}/{s['n']})"


def markdown(rep: dict) -> str:
    runs = rep["runs"]
    names = list(runs)
    first = runs[names[0]]
    L = [
        "# Answer evaluation",
        "",
        f"Answers come from the service's own `ask` path with caches off, generated by "
        f"`{first['model']}` (local, greedy decoding) from the top {first['k']} passages. "
        f"{first['n']} questions: the evaluation set of robotics-docs-rag, "
        f"{first['answerable']['correct']['n']} answerable and "
        f"{first['unanswerable']['abstained']['n']} that the corpus cannot answer.",
        "",
        "An answer to an answerable question is correct when the judge "
        f"(`{rep['primary_judge']}`) finds the reference answer's key facts in it; an "
        "abstention there is wrong. An unanswerable question is correct when the service "
        "abstains. Answers from Claude are not evaluated here: that requires an Anthropic "
        "API key.",
        "",
        "## Correctness",
        "",
        "| Retrieval | Correct, all | Correct, answerable | Abstained on answerable | "
        "Abstained on unanswerable | Retrieval found a relevant passage |",
        "|---|---|---|---|---|---|",
    ]
    for name in names:
        r = runs[name]
        a = r["answerable"]
        L.append(f"| {r['mode']} | {pct(r['overall'])} | {pct(a['correct'])} | "
                 f"{pct(a['abstained'])} | {pct(r['unanswerable']['abstained'])} | "
                 f"{pct(a['retrieval_hit'])} |")
    L += ["", "Split by whether a relevant passage was among the passages the model saw:", "",
          "| Retrieval | Correct when retrieved | Correct when not retrieved | "
          "Abstained when not retrieved |", "|---|---|---|---|"]
    for name in names:
        a = runs[name]["answerable"]
        L.append(f"| {runs[name]['mode']} | {pct(a['correct_when_retrieved'])} | "
                 f"{pct(a['correct_when_not_retrieved'])} | "
                 f"{pct(a['abstained_when_not_retrieved'])} |")
    L += ["",
          "A relevant passage is one from a gold document that contains the question's "
          "answer phrase, so \"not retrieved\" can still include passages that answer the "
          "question in other words.",
          "", "## Citations and form (answers given to answerable questions)", "",
          "| Retrieval | Has a citation | Cites a number that does not exist | "
          "Cites a relevant passage | Contains the gold answer phrase | Cut off at the token "
          "limit |", "|---|---|---|---|---|---|"]
    for name in names:
        g = runs[name]["given_answers"]
        L.append(f"| {runs[name]['mode']} | {pct(g['has_citation'])} | "
                 f"{pct(g['invalid_citation'])} | {pct(g['cites_relevant_passage'])} | "
                 f"{pct(g['contains_answer_key'])} | {pct(g['truncated'])} |")
    cats = sorted({c for r in runs.values() for c in r["by_category"]})
    L += ["", "## Correct by question category", "",
          "| Retrieval | " + " | ".join(cats) + " |", "|---|" + "---|" * len(cats)]
    for name in names:
        by = runs[name]["by_category"]
        L.append(f"| {runs[name]['mode']} | " + " | ".join(pct(by.get(c)) for c in cats) + " |")
    L += ["", "## Can the judge be trusted?", "",
          "Control items have a known verdict: the reference answer graded against itself "
          "(should be correct), another question's reference answer, and the service's "
          "\"cannot answer\" sentence (both should be incorrect). They are easy cases: they "
          "show that the judge is not broken, not that it is right on hard ones.", "",
          "| Judge | Reference vs itself | Another question's answer | Abstention sentence | "
          "Verdicts without a tag |", "|---|---|---|---|---|"]
    for tag, c in rep["controls"].items():
        cells = [f"{c[k]['as_expected']}/{c[k]['n']}" if k in c else "-"
                 for k in ("same", "other", "abstain")]
        L.append(f"| {tag} | " + " | ".join(cells)
                 + f" | {sum(v['unparsed'] for v in c.values())} |")
    if len(rep["judges"]) > 1:
        L += ["", "Correct on answerable questions according to each judge:", "",
              "| Retrieval | " + " | ".join(rep["judges"]) + " | Judges agree |",
              "|---|" + "---|" * (len(rep["judges"]) + 1)]
        for name in names:
            ag = rep["agreement"][name]
            L.append(f"| {runs[name]['mode']} | "
                     + " | ".join(pct(runs[name]["by_judge"][t]) for t in rep["judges"])
                     + f" | {ag['agree']}/{ag['n']} answers |")
        L += ["", "Agreement is counted over the answers both judges graded (abstentions "
              "are scored without a judge)."]
    if "gate" in rep:
        g = rep["gate"]
        L += ["", "## Regression gate", "",
              f"`llmeval-gate evals/answers_{g['baseline']}.csv "
              f"evals/answers_{g['candidate']}.csv` from llm-eval-harness, with its default "
              f"rule: fail when the mean drops by more than {g['max_drop']} and a one-sided "
              f"sign test gives p < {g['alpha']}.", "",
              "| Baseline | Candidate | Paired questions | Baseline mean | Candidate mean | "
              "Difference | 90 % interval | Better / worse / same | Sign test p | Verdict |",
              "|---|---|---|---|---|---|---|---|---|---|",
              f"| {g['baseline']} | {g['candidate']} | {g['n_items']} | "
              f"{g['baseline_mean']:.3f} | {g['candidate_mean']:.3f} | {g['delta']:+.3f} | "
              f"{g['ci'][0]:+.3f} to {g['ci'][1]:+.3f} | {g['n_better']} / {g['n_worse']} / "
              f"{g['n_same']} | {g['p_worse']:.3g} | {'pass' if g['passed'] else 'fail'} |"]
    return "\n".join(L) + "\n"
